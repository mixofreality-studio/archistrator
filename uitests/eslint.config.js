import js from '@eslint/js';
import globals from 'globals';
import tseslint from 'typescript-eslint';
import { defineConfig, globalIgnores } from 'eslint/config';

/**
 * Selector-discipline ESLint config for the archistrator scenario tests.
 *
 * Everything under generated/ is emitted by testgen from the committed
 * per-component test plan (deterministic component testing): the specs, the
 * Playwright config and the results reporter are `*.gen.ts` and are not linted
 * (they are regenerated, never edited — the drift gate holds them to the plan).
 * The one file the construction agent owns is generated/<component>/hooks.ts,
 * and it is black-box by construction: a hook must select DOM elements only by
 * published `data-testid` (`page.getByTestId(...)`) or accessible role/label
 * (`getByRole` / `getByLabel`) — never a raw CSS selector. One
 * `no-restricted-syntax` rule enforces that mechanically (not just by review):
 *
 *   "no locator() escape hatch" — Playwright's `.locator(<css|xpath>)` accepts
 *   an arbitrary selector and is exactly the un-cheatable-ness hole a hook must
 *   not use for element selection. It is banned outright. A genuine structural
 *   assertion with no testid/role to select by gets an explicit
 *   `eslint-disable-next-line no-restricted-syntax -- <reason>` at the call
 *   site rather than a blanket carve-out here.
 *
 * The testid strings a generated spec selects by come from the scenario
 * bindings in project.json (.phaseArtifacts.testPlan.<component>), so there is
 * no separate testid table for a hook to import from.
 */
const NO_LOCATOR = {
  selector: "CallExpression[callee.property.name='locator']",
  message:
    'Do not select elements with .locator(<css|xpath>) — use page.getByTestId(...), ' +
    'getByRole(...), or getByLabel(...) instead. If this is a genuine structural assertion ' +
    'with no testid/role to select by (e.g. counting react-flow DOM nodes), justify the escape ' +
    'with `eslint-disable-next-line no-restricted-syntax -- <reason>` rather than removing this rule.',
};

export default defineConfig([
  globalIgnores([
    'node_modules',
    'test-results',
    'playwright-report',
    'blob-report',
    // Regenerated by testgen from the committed test plan, never edited.
    'generated/**/*.gen.ts',
  ]),

  {
    files: ['**/*.ts'],
    extends: [js.configs.recommended, ...tseslint.configs.recommended],
    languageOptions: {
      ecmaVersion: 2022,
      sourceType: 'module',
      globals: globals.node,
    },
    rules: {
      'no-restricted-syntax': ['error', NO_LOCATOR],
    },
  },
]);
